#!/usr/bin/env node
/**
 * Asset checklist: compares the manifest with files under public/ and writes
 *   public/assets/storybook/manifest/asset-report.json
 *   ASSETS.md (human-readable checklist)
 * Status: available | placeholder (missing, generated stand-in shown) |
 *         optional (missing, nice-to-have) | missing (required, no stand-in).
 * Exit code 1 with `--strict` while any required asset is not available.
 */
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
// Node ≥ 22.18 / 23.6 strips TypeScript types natively; the manifest only uses type imports.
const { assetManifest } = await import('../src/features/storybook/scenes/scene-manifest.ts');

const rows = assetManifest.map((a) => {
  const present = existsSync(join(root, 'public', a.src));
  const status = present ? 'available' : a.placeholder ? 'placeholder' : a.requirement === 'optional' ? 'optional' : 'missing';
  return { id: a.id, status, requirement: a.requirement, kind: a.kind, critical: !!a.critical, path: `public${a.src}`, size: a.width ? `${a.width}×${a.height}` : '', description: a.description };
});

const counts = rows.reduce((acc, r) => ((acc[r.status] = (acc[r.status] ?? 0) + 1), acc), {});
const reportPath = join(root, 'public/assets/storybook/manifest/asset-report.json');
mkdirSync(dirname(reportPath), { recursive: true });
writeFileSync(reportPath, JSON.stringify({ generatedAt: new Date().toISOString(), counts, assets: rows }, null, 2) + '\n');

const icon = { available: '✅', placeholder: '🟨', optional: '⚪', missing: '❌' };
const md = [
  '# Storybook asset checklist',
  '',
  'Generated by `npm run assets:check` from `src/features/storybook/scenes/scene-manifest.ts`.',
  'Drop a file at its path to replace the placeholder — no code change needed.',
  '',
  `Summary: ${Object.entries(counts).map(([k, v]) => `${icon[k]} ${k}: ${v}`).join(' · ')}`,
  '',
  '| Status | Asset id | Req. | Critical | Export size | Path | Description |',
  '|---|---|---|---|---|---|---|',
  ...rows.map((r) => `| ${icon[r.status]} ${r.status} | \`${r.id}\` | ${r.requirement} | ${r.critical ? 'yes' : ''} | ${r.size} | \`${r.path}\` | ${r.description} |`),
  '',
].join('\n');
writeFileSync(join(root, 'ASSETS.md'), md);

console.table(rows.map(({ status, id, requirement, path }) => ({ status, id, requirement, path })));
console.log(counts);

if (process.argv.includes('--strict') && rows.some((r) => r.requirement === 'required' && r.status !== 'available')) {
  process.exitCode = 1;
}
